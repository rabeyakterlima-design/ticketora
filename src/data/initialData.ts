// Helper to generate 2x1 Sleeper berths (lower + upper deck, 30 berths)
const generateSleeperSeats = (layoutId: string) => {
  const rows = ['L1', 'L2', 'L3', 'L4', 'L5', 'U1', 'U2', 'U3', 'U4', 'U5'];
  const seats = [];
  // 15 berths lower, 15 berths upper
  for (let d = 0; d < 2; d++) {
    const deck = d === 0 ? ('lower' as const) : ('upper' as const);
    const prefix = d === 0 ? 'L' : 'U';
    for (let r = 1; r <= 5; r++) {
      // 1 single berth on left (window), aisle, 1 double berth on right
      seats.push({
        id: `seat-${layoutId}-${prefix}${r}A`,
        seat_number: `${prefix}${r}A`,
        deck,
        row: r,
        col: 1,
        seat_type: 'sleeper' as const,
        position: 'window' as const,
        fare_adjustment: 400,
        is_active: true,
      });
      seats.push({
        id: `seat-${layoutId}-${prefix}${r}B`,
        seat_number: `${prefix}${r}B`,
        deck,
        row: r,
        col: 3,
        seat_type: 'sleeper' as const,
        position: 'aisle' as const,
        fare_adjustment: 350,
        is_active: true,
      });
      seats.push({
        id: `seat-${layoutId}-${prefix}${r}C`,
        seat_number: `${prefix}${r}C`,
        deck,
        row: r,
        col: 4,
        seat_type: 'sleeper' as const,
        position: 'window' as const,
        fare_adjustment: 350,
        is_active: true,
      });
    }
  }
  return seats;
};

