// Helper to generate 2x2 layout seats (10 rows: A to J, 4 seats each)
const generate2x2Seats = (layoutId: string) => {
  const rows = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J'];
  const seats = [];
  for (let r = 0; r < rows.length; r++) {
    const rowChar = rows[r];
    for (let c = 1; c <= 4; c++) {
      seats.push({
        id: `seat-${layoutId}-${rowChar}${c}`,
        seat_number: `${rowChar}${c}`,
        deck: 'lower' as const,
        row: r + 1,
        col: c <= 2 ? c : c + 1, // aisle in middle
        seat_type: 'regular' as const,
        position: c === 1 || c === 4 ? ('window' as const) : ('aisle' as const),
        fare_adjustment: 0,
        is_active: true,
      });
    }
  }
  return seats;
};

